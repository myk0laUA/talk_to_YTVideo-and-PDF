// Deterministic report derived only from unmodified k6 JSON + server resource records.
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const read = async file => JSON.parse(await readFile(file, 'utf8'));
const median = values => [...values].sort((a, b) => a - b)[Math.floor(values.length / 2)];
const f = n => n.toFixed(2);
const records = {};
for (const mode of ['baseline', 'optimized']) {
  records[mode] = (await readFile(`benchmarks/${mode}.txt`, 'utf8')).split('\n').filter(s => s.startsWith('{')).map(s => JSON.parse(s));
  assert.ok(records[mode].some(r => r.status === 'PASS'), `${mode} must finish successfully`);
}
let text = 'Generated by: node scripts/bench/report.mjs\nAll latencies in milliseconds. Median of three runs at 25/50 VUs; others one run.\n\n';
text += '| VUs | Before req/s | After req/s | Before p95 | After p95 | Before/after errors |\n|---|---:|---:|---:|---:|---|\n';
const collected = {};
for (const vus of [1, 5, 10, 25, 50]) {
  collected[vus] = {};
  for (const mode of ['baseline', 'optimized']) {
    const runs = [];
    for (let repeat = 1; repeat <= (vus >= 25 ? 3 : 1); repeat++) {
      const label = `read-${vus}-r${repeat}`;
      const summary = await read(`benchmarks/raw/${mode}-${label}.json`);
      const resource = records[mode].find(r => r.label === label && r.resources)?.resources;
      assert.ok(resource);
      const m = summary.metrics;
      runs.push({ throughput: m.http_reqs.rate, requests: m.http_reqs.count, p50: m.http_req_duration.med,
        p95: m.http_req_duration['p(95)'], p99: m.http_req_duration['p(99)'], errorRate: m.http_req_failed.value,
        timeoutRate: m.request_timeouts.value, peakMiB: resource.peakRssBytes / 1048576, cpuCorePercent: resource.cpuCorePercent,
        queryEventsPerRead: resource.operations['db.query'].count / resource.operations['db.source.get'].count,
        meanRepositoryMs: resource.operations['db.source.get'].totalMs / resource.operations['db.source.get'].count,
        peakConnections: resource.peakConnections, peakWaiting: resource.peakWaiting });
    }
    collected[vus][mode] = { runs, median: Object.fromEntries(Object.keys(runs[0]).map(key => [key, median(runs.map(r => r[key]))])) };
  }
  const b = collected[vus].baseline.median, a = collected[vus].optimized.median;
  text += `| ${vus} | ${f(b.throughput)} | ${f(a.throughput)} | ${f(b.p95)} | ${f(a.p95)} | ${f(b.errorRate * 100)}% / ${f(a.errorRate * 100)}% |\n`;
}
text += '\n50 VU detailed comparison (median of each metric, not a fabricated representative run):\n\n| Metric | Before | After |\n|---|---:|---:|\n';
const b = collected[50].baseline.median, a = collected[50].optimized.median;
for (const key of ['throughput', 'p50', 'p95', 'p99', 'errorRate', 'timeoutRate', 'peakMiB', 'cpuCorePercent', 'queryEventsPerRead', 'meanRepositoryMs', 'peakConnections', 'peakWaiting'])
  text += `| ${key} | ${f(b[key])} | ${f(a[key])} |\n`;
text += `\np95 reduction: ${f((1 - a.p95 / b.p95) * 100)}%; throughput increase: ${f((a.throughput / b.throughput - 1) * 100)}%.\n`;
for (const mode of ['baseline', 'optimized']) {
  const runs = collected[50][mode].runs;
  text += `${mode} 50 VU ranges: throughput ${f(Math.min(...runs.map(r => r.throughput)))}–${f(Math.max(...runs.map(r => r.throughput)))} req/s; p95 ${f(Math.min(...runs.map(r => r.p95)))}–${f(Math.max(...runs.map(r => r.p95)))} ms.\n`;
  const failure = records[mode].find(r => r.failures);
  text += `${mode} failure/source probes: ${JSON.stringify(failure.failures)}\n`;
}
await writeFile('benchmarks/results.txt', text);
await writeFile('benchmarks/comparison.json', JSON.stringify(collected, null, 2) + '\n');
console.log(text);
